"""One list of test vectors shared by the Python tests, the C host test and the JavaScript
decoder test.  `python -m lorawan_payload_codec vectors` rewrites tests/vectors.json and
lib/payload_codec/test_vectors.h; tests/test_vectors.py fails if the committed files are stale.

The vectors are the 35 real incubator readings in examples/incubator_sample.json plus the edge
cases below (range limits, negative temperature, half steps in both signs, door open, alarm 31).
"""

from __future__ import annotations

import json
from pathlib import Path

from . import frames
from .compact import Reading

ROOT = Path(__file__).resolve().parents[2]
SAMPLE = ROOT / "examples" / "incubator_sample.json"
JSON_OUT = ROOT / "tests" / "vectors.json"
C_OUT = ROOT / "lib" / "payload_codec" / "test_vectors.h"

EDGE_CASES = [
    ("all zero / minimum battery", Reading(0.0, 0.0, 2.00, False, 0)),
    ("negative temperature", Reading(-12.34, 45.0, 3.30, False, 0)),
    ("compact temperature limits", Reading(-327.68, 100.0, 4.55, True, 31)),
    ("compact temperature maximum", Reading(327.67, 50.0, 3.00, False, 7)),
    ("door open, alarm 3", Reading(31.95, 70.5, 3.60, True, 3)),
    ("half steps round away from zero", Reading(26.85, 60.25, 3.615, False, 2)),
    ("negative half step rounds away from zero", Reading(-12.35, 0.25, 2.005, False, 0)),
    ("float trap: 26.85/0.1 is 268.49999 in binary", Reading(0.15, 99.75, 4.545, True, 1)),
    ("cold store", Reading(-25.0, 90.0, 2.50, False, 5)),
    ("hot overshoot", Reading(45.6, 33.0, 4.19, False, 2)),
]


def sample_readings() -> list[tuple[str, Reading]]:
    rows = json.loads(SAMPLE.read_text())["readings"]
    return [
        (
            f"incubator {row['iso']}",
            Reading(
                row["temperature_c"],
                row["humidity_pct"],
                row["battery_v"],
                row["door_open"],
                row["alarm_code"],
            ),
        )
        for row in rows
    ]


def build() -> list[dict]:
    out = []
    for name, r in sample_readings() + EDGE_CASES:
        entry: dict = {"name": name, "input": r.as_dict()}
        for fmt in frames.FORMATS:
            fport, payload = frames.encode(r, fmt)
            entry[fmt] = {
                "fport": fport,
                "hex": payload.hex(),
                "decoded": frames.decode(fport, payload).as_dict(),
            }
        out.append(entry)
    return out


def render_json(vectors: list[dict]) -> str:
    return json.dumps(vectors, indent=1) + "\n"


def render_c(vectors: list[dict]) -> str:
    lines = [
        "// Generated by `python -m lorawan_payload_codec vectors`; do not edit.",
        "// Inputs are given in the integer units the C encoder takes.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "  const char *name;",
        "  int32_t temp_centi;  // 0.01 degC",
        "  uint16_t hum_centi;  // 0.01 %",
        "  uint16_t batt_mv;",
        "  uint8_t door_open;",
        "  uint8_t alarm_code;",
        "  const char *compact_hex;",
        "  const char *cayenne_hex;",
        "} codec_vector_t;",
        "",
        f"#define CODEC_N_VECTORS {len(vectors)}",
        "static const codec_vector_t CODEC_VECTORS[CODEC_N_VECTORS] = {",
    ]
    for v in vectors:
        i = v["input"]
        lines.append(
            f'  {{"{v["name"]}", {round(i["temperature_c"] * 100)}, '
            f"{round(i['humidity_pct'] * 100)}, {round(i['battery_v'] * 1000)}, "
            f"{int(i['door_open'])}, {i['alarm_code']}, "
            f'"{v["compact"]["hex"]}", "{v["cayenne"]["hex"]}"}},'
        )
    lines += ["};", ""]
    return "\n".join(lines)


def write() -> tuple[Path, Path]:
    vectors = build()
    JSON_OUT.write_text(render_json(vectors))
    C_OUT.write_text(render_c(vectors))
    return JSON_OUT, C_OUT
